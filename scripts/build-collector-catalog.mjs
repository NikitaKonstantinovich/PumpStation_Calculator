import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { makeCollectorCatalog } from "../app/collector-catalog.ts";
import { mergeBindingSupplement } from "./binding-supplements.mjs";
import { mergeSealingSupplement } from "./sealing-supplement.mjs";
import { mergeInstrumentValve } from "./instrument-valve-supplement.mjs";
import { mergeReducerDimensions } from "./reducer-dimensions-supplement.mjs";
import { mergeCollarDimensions } from "../app/component-collar-dimensions.ts";
import { mergeFlangeDimensions } from "../app/flange-dimensions.ts";
import { mergeSensorNipples } from "../app/component-sensor-nipples.ts";
import { mergePipePainting } from "./pipe-painting-supplement.mjs";

const sourceUrl = new URL("../public/binding-components.json", import.meta.url);
const original = await readFile(sourceUrl, "utf8");
const supplier = JSON.parse(await readFile(new URL("../data/lunda-plugs.json", import.meta.url), "utf8"));
const seals = JSON.parse(await readFile(new URL("../data/sealing-supplement.json", import.meta.url), "utf8"));
const valve = JSON.parse(await readFile(new URL("../data/instrument-valve.json", import.meta.url), "utf8"));
const standards = JSON.parse(await readFile(new URL("../data/component-insert-standards.json", import.meta.url), "utf8"));
const collars = JSON.parse(await readFile(new URL("../data/collar-dimensions.json", import.meta.url), "utf8"));
const flanges = JSON.parse(await readFile(new URL("../data/flange-dimensions.json", import.meta.url), "utf8"));
const sensorNipples = JSON.parse(await readFile(new URL("../data/sensor-nipple-reference.json", import.meta.url), "utf8"));
const painting = JSON.parse(await readFile(new URL("../data/pipe-painting-prices.json", import.meta.url), "utf8"));
const data = mergePipePainting(mergeSensorNipples(mergeFlangeDimensions(mergeCollarDimensions(mergeReducerDimensions(mergeInstrumentValve(mergeSealingSupplement(mergeBindingSupplement(JSON.parse(original), supplier), seals), valve), standards), collars), flanges), sensorNipples), painting);
const source = JSON.stringify(data, null, 2) + "\n";
if (source !== original) await writeFile(sourceUrl, source);
const catalog = makeCollectorCatalog(data);
catalog.sourceSha256 = data.source.sha256;
// Hash the entire imported snapshot: price edits invalidate calculations too.
catalog.version = createHash("sha256").update(catalog.version).update(source).digest("hex");
await writeFile(new URL("../public/collector-catalog.json", import.meta.url), JSON.stringify(catalog, null, 2) + "\n");
console.log(`Collector catalogue: ${catalog.components.length} components, ${catalog.bolts.length} bolt sizes`);
