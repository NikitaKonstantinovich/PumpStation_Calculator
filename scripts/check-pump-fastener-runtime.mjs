// Read-only check of the real source adapter and the installed catalogue.
import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {readCatalogSnapshot} from '../services/local-storage/node-catalog.mjs';
import {loadTs} from '../tests/load-ts.mjs';
const out=resolve(process.argv[2]);
const snapshot=readCatalogSnapshot('E:/PumpStation_Calculator/database/catalog-v2/pumps.sqlite');
const {validateCatalogSnapshot}=await loadTs(new URL('../app/node-tools/catalog-schema.ts',import.meta.url));
validateCatalogSnapshot(snapshot);
const {pumpFasteners,bindFramePart}=await loadTs(new URL('../app/frame-calculation/components.ts',import.meta.url));
const {standHardware}=await loadTs(new URL('../app/frame-calculation/hardware.ts',import.meta.url));
const {readMounting}=await loadTs(new URL('../app/frame-calculation/project.ts',import.meta.url));
const base=JSON.parse(await readFile(new URL('../public/binding-components.json',import.meta.url),'utf8'));
const installed=JSON.parse(await readFile(join(out,'catalog-backup/frame-catalog-after.json'),'utf8'));
const items=[...base.items,...installed.items];
const pump=snapshot.items.find(r=>r.pump.model.replaceAll(' ','')==='MV1-3').pump;
const mounting=readMounting(pump.mounting.frameV1);assert.equal(mounting.clampHeightMm,38);
const selected=pumpFasteners(mounting,4,8,'pump-1',items);assert.equal(selected.issue,undefined);assert.match(selected.parts[0].name,/М12×65/);
const hardware=standHardware(true,600).map(p=>bindFramePart(p,items));
assert(hardware.every(p=>p.componentId));assert.equal(hardware.find(p=>p.role==='stand-left').quantity,1);assert.equal(hardware.find(p=>p.role==='stand-right').quantity,1);
const cdm=snapshot.items.find(r=>r.variantId==='CNP:CDM:1100092334').pump;
assert.equal(cdm.mounting.frameV1.boltDiameterMm,null);assert.equal(cdm.mounting.frameV1.clampHeightMm,null);
assert(cdm.mounting.frameV1.holes.every(h=>h.diameterMm===null));
const cdm15=snapshot.items.find(r=>r.variantId==='CNP:CDM:1100092321').pump;
const fitted=pumpFasteners(readMounting(cdm15.mounting.frameV1),5,8,'pump-1',items);
assert.equal(fitted.issue,undefined);assert.equal(fitted.parts[0].fastening.supportLift,0);assert.equal(fitted.parts[0].fastening.hole,16);
const result={snapshot:snapshot.id,executions:snapshot.items.length,mountings:snapshot.items.filter(r=>r.pump.mounting?.frameV1).length,fastenerRecords:snapshot.items.filter(r=>r.pump.mounting?.fastenersV1).length,sample:{model:pump.model,fasteners:selected.parts},cabinetHardware:hardware,cdm15:{model:cdm15.model,fasteners:fitted.parts}};
await writeFile(join(out,'runtime-check.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify({snapshot:result.snapshot,executions:result.executions,mountings:result.mountings,fastenerRecords:result.fastenerRecords,sampleBolt:selected.parts[0].name,hardwareBound:hardware.length}));
